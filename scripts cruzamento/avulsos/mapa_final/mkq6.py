rows = pickle.load(open('final_rows.pkl', 'rb'))
LIM = {'ALIM': 300, 'LOJ': 309, 'CONS': 235}
Q = []
for seg, rs in rows.items():
    for i, r in enumerate(rs, start=2):
        if i < LIM[seg] or r['cnpj']: continue
        n = norm(re.sub(r'\(.*?\)', '', r['fant']))
        ts = {n}
        for part in n.split(' / ') if '/' in r['fant'] else []: ts.add(norm(part))
        core = ' '.join(w for w in n.split() if w not in TIPO)
        if core and (len(core.split()) >= 2 or len(core) >= 5): ts.add(core)
        if ' ' in n: ts.add(n.replace(' ', ''))
        ts |= set(EXTRA.get(r['key'], []))
        ts = sorted(t for t in ts if t and len(t) >= 4)
        Q.append({'id': r['key'], 'terms': ts, 'cnpjs': [], 'st': r['conf'][:6], 'uf': r['uf_sede'], 'lin': i, 'fant': r['fant'], 'lojas': r['lojas']})
json.dump(Q, open('q6.json', 'w', encoding='utf8'), ensure_ascii=False)
print(len(Q), sum(len(q['terms']) for q in Q))
